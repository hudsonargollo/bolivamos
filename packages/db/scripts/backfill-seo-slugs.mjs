#!/usr/bin/env node
// One-off backfill for the `slug` column added by migration
// 0012_seo_slugs.sql (existing rows are NULL until this runs; new rows get
// a slug at create time via packages/db/src/slug.ts's generateUniqueSlug).
//
// Reads events/venues straight from D1 via `wrangler d1 execute --json`
// (same pattern as geocode-events.mjs) and writes an UPDATE statement per
// row to packages/db/seeds/seo-slugs.sql — apply with:
//   wrangler d1 execute bolivamos-db --local --file=packages/db/seeds/seo-slugs.sql
//   wrangler d1 execute bolivamos-db --remote --file=packages/db/seeds/seo-slugs.sql
//
// slugify() below is a plain-JS duplicate of packages/db/src/slug.ts's
// slugify() — this script doesn't run TS, so it can't import that module
// directly. Keep the two in sync by hand if the logic ever changes.
//
// Run: node packages/db/scripts/backfill-seo-slugs.mjs [--remote]

import { writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SEEDS_DIR = path.join(__dirname, "../seeds");
const SQL_OUT_PATH = path.join(SEEDS_DIR, "seo-slugs.sql");
const WEB_DIR = path.join(__dirname, "../../../apps/web");

const SOURCE = process.argv.includes("--remote") ? "--remote" : "--local";

function slugify(s) {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function sqlString(v) {
  return `'${String(v).replace(/'/g, "''")}'`;
}

function query(sql) {
  const raw = execSync(`npx wrangler d1 execute bolivamos-db ${SOURCE} --command "${sql}" --json`, {
    cwd: WEB_DIR,
    env: { ...process.env, CLOUDFLARE_ACCOUNT_ID: "cb27e1a67198789eb42d11ab90737652" },
    maxBuffer: 10 * 1024 * 1024,
  });
  return JSON.parse(raw.toString())[0].results;
}

// Assigns unique slugs within one table's rows in a single pass — taken
// slugs (already-backfilled or pre-existing) are seeded into `used` first so
// a fresh run never collides with rows a prior partial run already wrote.
function assignSlugs(rows, nameField, used) {
  const updates = [];
  for (const row of rows) {
    if (row.slug) {
      used.add(row.slug);
      continue;
    }
    const root = slugify(row[nameField] || "") || "item";
    let candidate = root;
    while (used.has(candidate)) {
      candidate = `${root}-${Math.random().toString(36).slice(2, 6)}`;
    }
    used.add(candidate);
    updates.push({ id: row.id, slug: candidate });
  }
  return updates;
}

function main() {
  console.log(`Reading events/venues from D1 (${SOURCE})...`);
  const events = query("SELECT id, title, slug FROM events");
  const venues = query("SELECT id, name, slug FROM venues");

  const eventUpdates = assignSlugs(events, "title", new Set());
  const venueUpdates = assignSlugs(venues, "name", new Set());

  const sqlLines = ["-- Generated by packages/db/scripts/backfill-seo-slugs.mjs — do not hand-edit."];
  for (const u of eventUpdates) sqlLines.push(`UPDATE events SET slug = ${sqlString(u.slug)} WHERE id = ${sqlString(u.id)};`);
  for (const u of venueUpdates) sqlLines.push(`UPDATE venues SET slug = ${sqlString(u.slug)} WHERE id = ${sqlString(u.id)};`);
  writeFileSync(SQL_OUT_PATH, sqlLines.join("\n") + "\n");

  console.log(`\nWrote ${SQL_OUT_PATH}`);
  console.log(`${eventUpdates.length}/${events.length} events need a slug, ${venueUpdates.length}/${venues.length} venues need a slug.`);
}

main();
